-- =============================================================================
-- AT Representaciones - esquema inicial
-- Montos en guaraníes (sin decimales) como BIGINT.
-- =============================================================================

-- ---------------------------------------------------------------- seguridad --
CREATE TABLE usuarios (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       varchar(40)  NOT NULL,
  nombre         varchar(120) NOT NULL,
  password_hash  text         NOT NULL,
  rol            varchar(20)  NOT NULL DEFAULT 'CAJERO' CHECK (rol IN ('ADMIN', 'CAJERO')),
  activo         boolean      NOT NULL DEFAULT true,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  updated_at     timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX usuarios_username_uq ON usuarios (lower(username));

-- Datos de la empresa y parámetros (fila única)
CREATE TABLE configuracion (
  id                  smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  razon_social        varchar(150) NOT NULL DEFAULT 'AT REPRESENTACIONES',
  ruc                 varchar(20)  NOT NULL DEFAULT '',
  direccion           varchar(200) NOT NULL DEFAULT '',
  telefono            varchar(60)  NOT NULL DEFAULT '',
  email               varchar(120) NOT NULL DEFAULT '',
  timbrado            varchar(20)  NOT NULL DEFAULT '',
  timbrado_vigencia   date,
  establecimiento     varchar(3)   NOT NULL DEFAULT '001',
  punto_expedicion    varchar(3)   NOT NULL DEFAULT '001',
  -- Contador correlativo sin huecos (se incrementa dentro de la transacción de la venta)
  ultimo_numero_factura integer  NOT NULL DEFAULT 0 CHECK (ultimo_numero_factura >= 0),
  comision_envio_pct  numeric(5,2) NOT NULL DEFAULT 5 CHECK (comision_envio_pct >= 0 AND comision_envio_pct <= 100),
  updated_at          timestamptz  NOT NULL DEFAULT now()
);

-- --------------------------------------------------------------- catálogos --
CREATE TABLE marcas (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(80) NOT NULL,
  activo      boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX marcas_descripcion_uq ON marcas (upper(descripcion));

CREATE TABLE impuestos (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(50) NOT NULL,
  tasa        smallint    NOT NULL UNIQUE CHECK (tasa IN (0, 5, 10))
);

CREATE TABLE depositos (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(80) NOT NULL,
  activo      boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX depositos_descripcion_uq ON depositos (upper(descripcion));

CREATE TABLE cajas (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(80) NOT NULL,
  activo      boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX cajas_descripcion_uq ON cajas (upper(descripcion));

CREATE TABLE operadoras (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(60) NOT NULL,
  activo      boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX operadoras_descripcion_uq ON operadoras (upper(descripcion));

CREATE TABLE tipos_carga (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(60) NOT NULL,
  activo      boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX tipos_carga_descripcion_uq ON tipos_carga (upper(descripcion));

-- ------------------------------------------------------------ personas --
CREATE TABLE clientes (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(120) NOT NULL,
  ruc         varchar(20)  NOT NULL,
  telefono    varchar(60),
  direccion   varchar(200),
  email       varchar(120),
  activo      boolean      NOT NULL DEFAULT true,
  created_at  timestamptz  NOT NULL DEFAULT now(),
  updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX clientes_ruc_uq ON clientes (upper(ruc));
CREATE INDEX clientes_nombre_idx ON clientes (upper(nombre));

CREATE TABLE proveedores (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(120) NOT NULL,
  ruc         varchar(20)  NOT NULL,
  telefono    varchar(60),
  direccion   varchar(200),
  email       varchar(120),
  activo      boolean      NOT NULL DEFAULT true,
  created_at  timestamptz  NOT NULL DEFAULT now(),
  updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX proveedores_ruc_uq ON proveedores (upper(ruc));

-- ------------------------------------------------------------- inventario --
CREATE TABLE productos (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo         varchar(50)  NOT NULL,
  descripcion    varchar(150) NOT NULL,
  marca_id       integer      NOT NULL REFERENCES marcas (id),
  impuesto_id    integer      NOT NULL REFERENCES impuestos (id),
  precio_compra  bigint       NOT NULL DEFAULT 0 CHECK (precio_compra >= 0),
  precio_venta   bigint       NOT NULL DEFAULT 0 CHECK (precio_venta >= 0),
  stock_minimo   integer      NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
  imagen         bytea,
  imagen_mime    varchar(50),
  activo         boolean      NOT NULL DEFAULT true,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  updated_at     timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX productos_codigo_uq ON productos (upper(codigo));
CREATE INDEX productos_descripcion_idx ON productos (upper(descripcion));

CREATE TABLE stock (
  producto_id  integer NOT NULL REFERENCES productos (id),
  deposito_id  integer NOT NULL REFERENCES depositos (id),
  cantidad     integer NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
  PRIMARY KEY (producto_id, deposito_id)
);

-- Kardex: todo cambio de stock queda registrado
CREATE TABLE stock_movimientos (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id      integer     NOT NULL REFERENCES productos (id),
  deposito_id      integer     NOT NULL REFERENCES depositos (id),
  tipo             varchar(30) NOT NULL,
  cantidad         integer     NOT NULL,
  saldo            integer     NOT NULL,
  referencia_tipo  varchar(30),
  referencia_id    integer,
  usuario_id       integer     NOT NULL REFERENCES usuarios (id),
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX stock_movimientos_producto_idx ON stock_movimientos (producto_id, created_at DESC);

-- ------------------------------------------------------------------ caja --
CREATE TABLE sesiones_caja (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caja_id                  integer     NOT NULL REFERENCES cajas (id),
  usuario_id               integer     NOT NULL REFERENCES usuarios (id),
  estado                   varchar(10) NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'CERRADA')),
  abierta_at               timestamptz NOT NULL DEFAULT now(),
  monto_apertura           bigint      NOT NULL CHECK (monto_apertura >= 0),
  cerrada_at               timestamptz,
  cerrada_por              integer REFERENCES usuarios (id),
  declarado_efectivo       bigint,
  declarado_tarjeta        bigint,
  declarado_cheque         bigint,
  declarado_transferencia  bigint,
  total_esperado           bigint,
  total_declarado          bigint,
  diferencia               bigint,
  observacion              varchar(300)
);
CREATE UNIQUE INDEX sesiones_caja_abierta_caja_uq ON sesiones_caja (caja_id) WHERE estado = 'ABIERTA';
CREATE UNIQUE INDEX sesiones_caja_abierta_usuario_uq ON sesiones_caja (usuario_id) WHERE estado = 'ABIERTA';

CREATE TABLE movimientos_caja (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sesion_caja_id   integer      NOT NULL REFERENCES sesiones_caja (id),
  tipo             varchar(10)  NOT NULL CHECK (tipo IN ('INGRESO', 'EGRESO')),
  concepto         varchar(40)  NOT NULL,
  medio_pago       varchar(20)  NOT NULL DEFAULT 'EFECTIVO'
                   CHECK (medio_pago IN ('EFECTIVO', 'TARJETA', 'CHEQUE', 'TRANSFERENCIA')),
  monto            bigint       NOT NULL CHECK (monto > 0),
  descripcion      varchar(200),
  referencia_tipo  varchar(30),
  referencia_id    integer,
  anulado          boolean      NOT NULL DEFAULT false,
  usuario_id       integer      NOT NULL REFERENCES usuarios (id),
  created_at       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX movimientos_caja_sesion_idx ON movimientos_caja (sesion_caja_id);
CREATE INDEX movimientos_caja_ref_idx ON movimientos_caja (referencia_tipo, referencia_id);

-- ---------------------------------------------------------------- ventas --
CREATE TABLE ventas (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nro_factura       varchar(15) NOT NULL UNIQUE,
  fecha             date        NOT NULL DEFAULT current_date,
  cliente_id        integer     NOT NULL REFERENCES clientes (id),
  deposito_id       integer     NOT NULL REFERENCES depositos (id),
  condicion         varchar(10) NOT NULL CHECK (condicion IN ('CONTADO', 'CREDITO')),
  cuotas            smallint    NOT NULL DEFAULT 1 CHECK (cuotas BETWEEN 1 AND 60),
  intervalo_dias    smallint    NOT NULL DEFAULT 30 CHECK (intervalo_dias BETWEEN 1 AND 365),
  medio_pago        varchar(20) CHECK (medio_pago IN ('EFECTIVO', 'TARJETA', 'CHEQUE', 'TRANSFERENCIA')),
  total_exenta      bigint      NOT NULL DEFAULT 0,
  total_gravada5    bigint      NOT NULL DEFAULT 0,
  total_gravada10   bigint      NOT NULL DEFAULT 0,
  total_iva5        bigint      NOT NULL DEFAULT 0,
  total_iva10       bigint      NOT NULL DEFAULT 0,
  total             bigint      NOT NULL CHECK (total > 0),
  estado            varchar(10) NOT NULL DEFAULT 'EMITIDA' CHECK (estado IN ('EMITIDA', 'ANULADA')),
  sesion_caja_id    integer     NOT NULL REFERENCES sesiones_caja (id),
  usuario_id        integer     NOT NULL REFERENCES usuarios (id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  anulada_at        timestamptz,
  anulada_por       integer REFERENCES usuarios (id),
  motivo_anulacion  varchar(200)
);
CREATE INDEX ventas_fecha_idx ON ventas (fecha DESC);
CREATE INDEX ventas_cliente_idx ON ventas (cliente_id);

CREATE TABLE venta_detalles (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id         integer  NOT NULL REFERENCES ventas (id) ON DELETE CASCADE,
  producto_id      integer  NOT NULL REFERENCES productos (id),
  cantidad         integer  NOT NULL CHECK (cantidad > 0),
  precio_unitario  bigint   NOT NULL CHECK (precio_unitario >= 0),
  costo_unitario   bigint   NOT NULL DEFAULT 0,
  tasa_iva         smallint NOT NULL CHECK (tasa_iva IN (0, 5, 10)),
  subtotal         bigint   NOT NULL
);
CREATE INDEX venta_detalles_venta_idx ON venta_detalles (venta_id);
CREATE INDEX venta_detalles_producto_idx ON venta_detalles (producto_id);

CREATE TABLE cuentas_cobrar (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id     integer     NOT NULL REFERENCES ventas (id),
  cliente_id   integer     NOT NULL REFERENCES clientes (id),
  nro_cuota    smallint    NOT NULL,
  vencimiento  date        NOT NULL,
  monto        bigint      NOT NULL CHECK (monto > 0),
  saldo        bigint      NOT NULL CHECK (saldo >= 0),
  estado       varchar(10) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'PAGADA', 'ANULADA')),
  UNIQUE (venta_id, nro_cuota),
  CHECK (saldo <= monto)
);
CREATE INDEX cuentas_cobrar_cliente_idx ON cuentas_cobrar (cliente_id) WHERE estado = 'PENDIENTE';

CREATE TABLE cobros (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id        integer     NOT NULL REFERENCES clientes (id),
  total             bigint      NOT NULL CHECK (total > 0),
  medio_pago        varchar(20) NOT NULL CHECK (medio_pago IN ('EFECTIVO', 'TARJETA', 'CHEQUE', 'TRANSFERENCIA')),
  estado            varchar(10) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'ANULADO')),
  sesion_caja_id    integer     NOT NULL REFERENCES sesiones_caja (id),
  usuario_id        integer     NOT NULL REFERENCES usuarios (id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  anulado_at        timestamptz,
  anulado_por       integer REFERENCES usuarios (id)
);

CREATE TABLE cobro_detalles (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cobro_id           integer NOT NULL REFERENCES cobros (id) ON DELETE CASCADE,
  cuenta_cobrar_id   integer NOT NULL REFERENCES cuentas_cobrar (id),
  monto              bigint  NOT NULL CHECK (monto > 0)
);

-- --------------------------------------------------------------- compras --
CREATE TABLE compras (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_factura    varchar(30) NOT NULL,
  fecha             date        NOT NULL DEFAULT current_date,
  proveedor_id      integer     NOT NULL REFERENCES proveedores (id),
  deposito_id       integer     NOT NULL REFERENCES depositos (id),
  condicion         varchar(10) NOT NULL CHECK (condicion IN ('CONTADO', 'CREDITO')),
  total_exenta      bigint      NOT NULL DEFAULT 0,
  total_gravada5    bigint      NOT NULL DEFAULT 0,
  total_gravada10   bigint      NOT NULL DEFAULT 0,
  total_iva5        bigint      NOT NULL DEFAULT 0,
  total_iva10       bigint      NOT NULL DEFAULT 0,
  total             bigint      NOT NULL CHECK (total > 0),
  estado            varchar(10) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'ANULADA')),
  usuario_id        integer     NOT NULL REFERENCES usuarios (id),
  created_at        timestamptz NOT NULL DEFAULT now(),
  anulada_at        timestamptz,
  anulada_por       integer REFERENCES usuarios (id),
  motivo_anulacion  varchar(200)
);
CREATE UNIQUE INDEX compras_factura_uq ON compras (proveedor_id, upper(numero_factura)) WHERE estado = 'ACTIVA';

CREATE TABLE compra_detalles (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id       integer  NOT NULL REFERENCES compras (id) ON DELETE CASCADE,
  producto_id     integer  NOT NULL REFERENCES productos (id),
  cantidad        integer  NOT NULL CHECK (cantidad > 0),
  costo_unitario  bigint   NOT NULL CHECK (costo_unitario >= 0),
  tasa_iva        smallint NOT NULL CHECK (tasa_iva IN (0, 5, 10)),
  subtotal        bigint   NOT NULL
);
CREATE INDEX compra_detalles_compra_idx ON compra_detalles (compra_id);

-- --------------------------------------------------------------- ajustes --
CREATE TABLE ajustes (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo         varchar(10)  NOT NULL CHECK (tipo IN ('ALTA', 'BAJA')),
  deposito_id  integer      NOT NULL REFERENCES depositos (id),
  observacion  varchar(200) NOT NULL,
  usuario_id   integer      NOT NULL REFERENCES usuarios (id),
  created_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE ajuste_detalles (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ajuste_id    integer NOT NULL REFERENCES ajustes (id) ON DELETE CASCADE,
  producto_id  integer NOT NULL REFERENCES productos (id),
  cantidad     integer NOT NULL CHECK (cantidad > 0)
);

-- ------------------------------------------------- saldos y billeteras --
-- Cuenta RECARGA: saldo para vender recargas. Cuenta BILLETERA: dinero electrónico.
CREATE TABLE saldos_operadora (
  operadora_id  integer     NOT NULL REFERENCES operadoras (id),
  cuenta        varchar(10) NOT NULL CHECK (cuenta IN ('RECARGA', 'BILLETERA')),
  saldo         bigint      NOT NULL DEFAULT 0 CHECK (saldo >= 0),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (operadora_id, cuenta)
);

CREATE TABLE saldo_movimientos (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operadora_id      integer      NOT NULL REFERENCES operadoras (id),
  cuenta            varchar(10)  NOT NULL CHECK (cuenta IN ('RECARGA', 'BILLETERA')),
  tipo              varchar(30)  NOT NULL,
  monto             bigint       NOT NULL,
  saldo_resultante  bigint       NOT NULL,
  referencia_tipo   varchar(30),
  referencia_id     integer,
  observacion       varchar(200),
  usuario_id        integer      NOT NULL REFERENCES usuarios (id),
  created_at        timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX saldo_movimientos_idx ON saldo_movimientos (operadora_id, cuenta, created_at DESC);

CREATE TABLE ventas_saldo (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operadora_id    integer     NOT NULL REFERENCES operadoras (id),
  tipo_carga_id   integer     NOT NULL REFERENCES tipos_carga (id),
  numero_destino  varchar(20) NOT NULL,
  monto           bigint      NOT NULL CHECK (monto > 0),
  estado          varchar(10) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'ANULADA')),
  sesion_caja_id  integer     NOT NULL REFERENCES sesiones_caja (id),
  usuario_id      integer     NOT NULL REFERENCES usuarios (id),
  created_at      timestamptz NOT NULL DEFAULT now(),
  anulada_at      timestamptz,
  anulada_por     integer REFERENCES usuarios (id)
);
CREATE INDEX ventas_saldo_fecha_idx ON ventas_saldo (created_at DESC);

CREATE TABLE movimientos_billetera (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operadora_id    integer      NOT NULL REFERENCES operadoras (id),
  tipo            varchar(20)  NOT NULL CHECK (tipo IN ('ENVIO', 'RETIRO', 'CARGA', 'PAGO_SERVICIO')),
  nro_boleta      varchar(40),
  nro_envia       varchar(20),
  nro_recibe      varchar(20),
  nombre          varchar(120),
  ci              varchar(20),
  servicio        varchar(120),
  referencia      varchar(100),
  monto           bigint       NOT NULL CHECK (monto > 0),
  comision        bigint       NOT NULL DEFAULT 0 CHECK (comision >= 0),
  total           bigint       NOT NULL CHECK (total > 0),
  estado          varchar(10)  NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'ANULADO')),
  sesion_caja_id  integer      NOT NULL REFERENCES sesiones_caja (id),
  usuario_id      integer      NOT NULL REFERENCES usuarios (id),
  created_at      timestamptz  NOT NULL DEFAULT now(),
  anulado_at      timestamptz,
  anulado_por     integer REFERENCES usuarios (id)
);
CREATE INDEX movimientos_billetera_fecha_idx ON movimientos_billetera (created_at DESC);
