    private void cargar_tabla() {
        DefaultTableModel tab = (DefaultTableModel) tabla.getModel();
        tab.setRowCount(0);
        
        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos("SELECT id_cliente, cli_nombre, cli_ruc, cli_telef, cli_direc, id_estado\n"
                    + "  FROM public.cliente where id_estado=1 and (cli_nombre ::text ilike'%" + txtbuscar.getText() + "%' or cli_ruc ::text ilike'%" + txtbuscar.getText() + "%' ) ORDER BY cli_nombre DESC  ");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("id_cliente"),
                    bd.resultado.getString("cli_nombre"),
                    bd.resultado.getString("cli_ruc"),
                    bd.resultado.getString("cli_telef"),
                    bd.resultado.getString("cli_direc")});
                
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
        }
    }
