    private void btgrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgrabarActionPerformed
        if (txtnombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe Ingresar Nombre", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtnombre.requestFocus();
            return;
        }
        if (txtruc.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe Ingresar Ruc", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtruc.requestFocus();
            return;
        }

        //grabar
        if (accion.equals("nuevo")) {
            
            for (int i = 0; i < tabla.getRowCount(); i++) {
                String vcod = tabla.getValueAt(i, 2).toString();
                if (vcod.equals(txtruc.getText())) {
                    JOptionPane.showMessageDialog(null, "Verifique Ruc ya Existe", "Error", JOptionPane.ERROR_MESSAGE);
                    txtruc.requestFocus();
                    txtruc.setSelectionStart(0);
                    txtruc.setSelectionColor(Color.red);
                    return;
                }
            }
            //guardar
            try {
                String sql = "INSERT INTO public.cliente(\n"
                        + "            id_cliente, cli_nombre, cli_ruc, cli_telef, cli_direc, id_estado)\n"
                        + "    VALUES (?, ?, ?, ?, ?, ?);";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(1, Integer.parseInt(txtid.getText()));
                p.setString(2, txtnombre.getText());
                p.setString(3, txtruc.getText());
                p.setString(4, txttelefono.getText());
                p.setString(5, txtdireccion.getText());
                p.setInt(6, 1);
                p.execute();
                
                cargar_tabla();
                
                btcancelar.doClick();
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error al guardar los datos" + e);
            }

//dispose();
        } else {
//          modificar
            try {
                
                String sql = "UPDATE public.cliente\n"
                        + "   SET  cli_nombre=?, cli_ruc=?, cli_telef=?, cli_direc=?, \n"
                        + "       id_estado=?\n"
                        + " WHERE id_cliente=?;";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(6, Integer.parseInt(txtid.getText()));
                p.setString(1, txtnombre.getText());
                p.setString(2, txtruc.getText());
                p.setString(3, txttelefono.getText());
                p.setString(4, txtdireccion.getText());
                p.setInt(5, 1);
                
                p.execute();
                //cargar la tabla una vez registrado     
                cargar_tabla();
                
                btcancelar.doClick();
                
            } catch (Exception e) {
//                System.out.println(e);
                JOptionPane.showMessageDialog(null, "Verifique Ruc ya Existe", "Error", JOptionPane.ERROR_MESSAGE);
                
            }
            
        }
        if (ventas.bandera == 1) {
            new buscador_cliente(null, true).setVisible(true);
            dispose();
        }
    }//GEN-LAST:event_btgrabarActionPerformed

