    private void btnuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnuevoActionPerformed
        caja ca = new caja();
        if (ca.tabla.getRowCount() == 0) {
            JOptionPane.showMessageDialog(null, "Realizar Apertura de Caja");
            return;
        } else {
            
            accion = "nuevo";
            bd.retornar_ultimo("apert_cierre", "id_apertcierre", txtapertura);
            bd.autonumerico("movimiento_billetera", "id_movimientobilletera", txtid);
            txtfecha.setText(fec.format(new Date()));
            txthora.setText(hora.format(new Date()));
            cboperadora.setEnabled(true);
            cbtipo.requestFocus();
            btnuevo.setEnabled(false);
            btanular.setEnabled(false);
            btcancelar.setEnabled(true);
        }
    }//GEN-LAST:event_btnuevoActionPerformed

    private void btanularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btanularActionPerformed
        bandera = 1;
        new buscador_movbilletera(null, true).setVisible(true);
        bandera = 0;
        if (!txtid.getText().isEmpty()) {
            recuperar_datos();
        }
        if (txtid.getText().isEmpty()) {
//                JOptionPane.showMessageDialog(null, "error");
        } else {
            
            int mensaje = JOptionPane.showConfirmDialog(null, "Desea Anular Billetera", "Atencion", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
            //si es 0 presiono la opcion de si, si es 1 no

            if (mensaje == 0) {
                if (buscador_movbilletera.tabla.getRowCount() == 0) {
                    JOptionPane.showMessageDialog(null, "No hay ninguna Billetera para anular");
                } else {
                    try {
                        String sql = "UPDATE public.movimiento_billetera\n"
                                + "   SET  id_estado=?\n"
                                + " WHERE id_movimientobilletera=?;";
                        PreparedStatement eli = bd.conexion.prepareStatement(sql);
                        eli.setInt(1, 2);
                        eli.setInt(2, Integer.parseInt(txtid.getText()));
                        eli.execute();
                        eli.close();
                        btcancelar.setEnabled(true);
                        btcancelar.doClick();
                    } catch (SQLException ex) {
                        System.out.println("error de " + ex);
                        JOptionPane.showMessageDialog(null, "Error al anular");
                        
                    }
                    
                }
            }
            if (mensaje == 1) {
                btcancelar.setEnabled(true);
                btcancelar.doClick();
                btcancelar.doClick();
            }
        }
    }//GEN-LAST:event_btanularActionPerformed

