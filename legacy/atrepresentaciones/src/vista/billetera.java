    private void recuperar_datos() {
        try {
            bd.listar_datos("SELECT id_movimientobilletera, mov_fecha, mov_numero, id_tipobilletera, \n"
                    + "       mov_nrorecibe, mov_nroenvia, mov_nombre, mov_ci, mov_pagoservicios, \n"
                    + "       mov_pagoservmonto, mov_totalenvio_retiro, mov_comision, mov_referenciatrans, \n"
                    + "       id_estado, id_usuario,mov_total\n"
                    + "  FROM public.movimiento_billetera where id_movimientobilletera  ='" + txtid.getText() + "'");
            if (bd.resultado.next()) {
                txtid.setText(bd.resultado.getString("id_movimientobilletera"));
                txtfecha.setText(bd.resultado.getString("mov_fecha"));
                txtnroboleta.setText(bd.resultado.getString("mov_numero"));
                txtnrorecibe.setText(bd.resultado.getString("mov_nrorecibe"));
                txtnroenvia.setText(bd.resultado.getString("mov_nroenvia"));
                
                txtnombre.setText(bd.resultado.getString("mov_nombre"));
                txtci.setText(bd.resultado.getString("mov_ci"));
                txtservicio.setText(bd.resultado.getString("mov_pagoservicios"));
                txtmontoservicios.setText(bd.resultado.getString("mov_pagoservmonto"));
                txttotalgeneral.setText(bd.resultado.getString("mov_total"));
                txttotal.setText(bd.resultado.getString("mov_totalenvio_retiro"));
                txtcomision.setText(bd.resultado.getString("mov_comision"));
                //suma();
                txtreferencia.setText(bd.resultado.getString("mov_referenciatrans"));
                
            }
        } catch (Exception e) {
            
            JOptionPane.showMessageDialog(null, "Error al recuperar la tabla" + e);
        }
        
    }
    
