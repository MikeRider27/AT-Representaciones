    private void recuperar_articulos() {

        for (int i = 0; i < detalle.getRowCount(); i++) {
            String vcod = detalle.getValueAt(i, 0).toString();
            if (vcod.equals(txtcodigo.getText())) {
                JOptionPane.showMessageDialog(null, "El producto ya fue seleccionado\n Verifique Codigo", "Error", JOptionPane.ERROR_MESSAGE);
                txtcodigo.requestFocus();
                txtcodigo.setSelectionStart(0);
                txtcodigo.setSelectionColor(Color.red);
                return;
            }
        }
        try {
            bd.listar_datos(" SELECT s.id_deposito as deposito, s.id_prod as idproducto, s.stock_cantidad as cantidad,p.prod_descri as descripcion,p.prod_cod as codigo,\n"
                    + "p.prod_precioc as prociocompra, p.prod_preciov as precioventa, p.prod_imagen as imagen, p.id_impuesto as impuesto\n"
                    + "  FROM stock s\n"
                    + "  inner join productos p on p.id_prod = s.id_prod\n"
                    + "   where p.prod_cod ='" + txtcodigo.getText() + "'");
            if (bd.resultado.next()) {
                txtdescripcion.setText(bd.resultado.getString("descripcion"));
                txtidcodigo.setText(bd.resultado.getString("idproducto"));
                txtpreciov.setText(bd.resultado.getString("precioventa"));
                txtprecioc.setText(bd.resultado.getString("prociocompra"));
                txtstock.setText(bd.resultado.getString("cantidad"));
                txtimpuesto.setText(bd.resultado.getString("impuesto"));
                txtcantidad.setEnabled(true);
                txtcantidad.requestFocus();

            } else {
                txtcodigo.requestFocus();
                txtcodigo.setSelectionStart(0);
                txtcodigo.setSelectionColor(Color.red);
                JOptionPane.showMessageDialog(null, "No existe codigo ingresado\nPor favor verifique", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Error al recuperar la tabla" + e);
        }

    }

    private String convertir_fecha(String fecha) {

// 25-08-2016
        String dia = "", mes = "", anho = "";

        dia = fecha.substring(0, 2);
        mes = fecha.substring(3, 5);
        anho = fecha.substring(6, 10);
        fecha = anho + "-" + mes + "-" + dia;

        return fecha;
    }
