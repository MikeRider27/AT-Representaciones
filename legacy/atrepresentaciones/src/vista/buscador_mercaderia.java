    private void cargar_tabla() {

        DefaultTableModel tab = (DefaultTableModel) tabla.getModel();
        tab.setRowCount(0);
//        DecimalFormat formato = new DecimalFormat("#,##0");
        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos("SELECT  s.id_prod,p.prod_cod as codigo, p.prod_descri as descripcion,p.prod_preciov as precioventa,\n"
                    + "s.stock_cantidad as cantidad, p.prod_imagen as imagen, m.mar_descri as marca\n"
                    + "                    from stock s \n"
                    + "                    inner join productos p on p.id_prod = s.id_prod\n"
                    + "                    inner join marca m on m.id_marca = p.id_marca\n"
                    + "where p.prod_cod ::text ilike'%" + txtbuscar.getText() + "%' or p.prod_descri ::text ilike'%" + txtbuscar.getText() + "%'  ;");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("codigo"),
                    bd.resultado.getString("descripcion"),
                    bd.resultado.getString("marca"),
                    bd.resultado.getString("precioventa"),
                    bd.resultado.getString("cantidad"),
                    bd.resultado.getString("id_prod")});

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
            System.out.println("error en" + e);
        }

    }

