    private void recuperar_imagen() {
        ImageIcon foto;
        InputStream is;
//        String nombre;
        try {
            bd.listar_datos("SELECT prod_imagen  FROM public.productos where id_prod=" + txtid.getText() + "");

            while (bd.resultado.next()) {

                is = bd.resultado.getBinaryStream(1);
//                nombre = bd.resultado.getString(2);

                BufferedImage bi = ImageIO.read(is);
                foto = new ImageIcon(bi);

                Image img = foto.getImage();
                Image newimg = img.getScaledInstance(180, 150, java.awt.Image.SCALE_SMOOTH);

                ImageIcon newicon = new ImageIcon(newimg);
                lblfoto.setIcon(newicon);
//                txtdescripcion.setText(nombre);

            }

        } catch (Exception e) {

            lblfoto.setIcon(null);
            // System.out.println("error en la imagen" + e);
        }

    }

    private void cargar_tabla() {

        DefaultTableModel tab = (DefaultTableModel) tabla.getModel();
        tab.setRowCount(0);

        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos("select s.id_prod , p.prod_cod as codigo, p.prod_descri as descripcion, p.prod_precioc as preciocompra, p.prod_preciov as precioventa,"
                    + "s.stock_cantidad as cantidad, p.prod_imagen as imagen, \n"
                    + "       m.mar_descri as marca\n"
                    + "from stock s \n"
                    + "inner join productos p on p.id_prod = s.id_prod\n"
                    + "inner join marca m on m.id_marca = p.id_marca "
                    + "where p.prod_cod ::text like'%" + txtbuscar.getText() + "%' or p.prod_descri ::text ilike'%" + txtbuscar.getText() + "%'  ;");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("id_prod"),
                    bd.resultado.getString("codigo"),
                    bd.resultado.getString("descripcion"),
                    bd.resultado.getString("marca"),
                    bd.resultado.getString("preciocompra"),
                    bd.resultado.getString("precioventa"),
                    bd.resultado.getString("cantidad")});

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
            System.out.println("error en" + e);
        }

    }

    private void recuperar_marca() {
        try {
            bd.listar_datos("SELECT id_marca, mar_descri\n"
                    + "  FROM public.marca where id_marca =" + txtidmarca.getText() + "");
            if (bd.resultado.next()) {
                txtmarca.setText(bd.resultado.getString("mar_descri"));
                // btimagen.setEnabled(true);
                txtpreciov.setEnabled(true);
                txtpreciov.requestFocus();
                btgrabar.setEnabled(true);

            } else {
                txtidmarca.requestFocus();
                txtidmarca.setSelectionStart(0);
                txtidmarca.setSelectionColor(Color.red);
                JOptionPane.showMessageDialog(null, "No existe codigo ingresado\nPor favor verifique", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {

            JOptionPane.showMessageDialog(null, "Error al recuperar la tabla" + e);
        }
    }

    private void recuperar_datos() {
        try {
            bd.listar_datos("select s.id_prod , p.prod_cod as codigo, p.prod_descri as descripcion, p.prod_precioc as preciocompra, p.prod_preciov as precioventa,"
                    + "s.stock_cantidad as cantidad, p.prod_imagen as imagen, \n"
                    + "       p.id_marca as marca\n"
                    + "from stock s \n"
                    + "inner join productos p on p.id_prod = s.id_prod\n"
                    + "where s.id_prod=" + txtid.getText() + ";");
            if (bd.resultado.next()) {
                txtcodigo.setText(bd.resultado.getString("codigo"));
                txtdescripcion.setText(bd.resultado.getString("descripcion"));
                txtidmarca.setText(bd.resultado.getString("marca"));
                txtprecioc.setText(bd.resultado.getString("preciocompra"));
                txtpreciov.setText(bd.resultado.getString("precioventa"));
                txtcant.setText(bd.resultado.getString("cantidad"));

            }
            recuperar_imagen();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al recuperar la tabla" + e);
        }

    }
