    private void btgrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgrabarActionPerformed

        if (txtcodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Ingrese codigo para su producto", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtcodigo.requestFocus();
            return;
        }
        if (txtdescripcion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Ingrese Nombre de Producto", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtdescripcion.requestFocus();
            return;
        }
        if (txtidmarca.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Ingrese Marca de Producto", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtidmarca.requestFocus();
            return;
        }
        if (txtpreciov.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Verifique Precio de Venta", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtpreciov.requestFocus();
            return;
        }
        if (lblfoto.getIcon() == null) {
            JOptionPane.showMessageDialog(null, "Favor Ingrese Imagen de Producto \n "
                    + "Si no tiene imagen del producto seleccione sin imagen", "Informe", JOptionPane.INFORMATION_MESSAGE);
            btimagen.requestFocus();
            return;
        }
//        //grabar

        if (accion.equals("nuevo")) {
            //guardar
            try {

                String sql = "INSERT INTO public.productos(\n"
                        + "            id_prod, prod_cod, prod_descri, prod_precioc, prod_preciov, prod_imagen, \n"
                        + "            id_marca, id_impuesto, id_estado, id_deposito)\n"
                        + "    VALUES (?, ?, ?, ?, ?, ?, \n"
                        + "            ?, ?, ?, ?);";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(1, Integer.parseInt(txtid.getText()));
                p.setString(2, txtcodigo.getText());
                p.setString(3, txtdescripcion.getText());
                p.setString(4, txtprecioc.getText());
                p.setString(5, txtpreciov.getText());
                p.setBinaryStream(6, fis, longitudBytes);
                p.setInt(7, Integer.parseInt(txtidmarca.getText()));
                p.setInt(8, 1);
                p.setInt(9, 1);
                p.setInt(10, 1);
                p.execute();
                p.close();

                // INSERT AL STOCK
                String sql2 = "INSERT INTO public.stock(\n"
                        + "            id_deposito, id_prod, stock_cantidad)\n"
                        + "    VALUES (?, ?, ?);";
                PreparedStatement p2 = bd.conexion.prepareStatement(sql2);
                p2.setInt(1, 1);
                p2.setInt(2, Integer.parseInt(txtid.getText()));
                p2.setInt(3, Integer.parseInt(txtcant.getText()));
                p2.execute();
                p2.close();

                JOptionPane.showMessageDialog(null, "Registro Guardado", "Informe", JOptionPane.INFORMATION_MESSAGE);
                cargar_tabla();
                btcancelar.doClick();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error al guardar los datos" + e);
                System.out.println("error" + e);
            }

            //dispose();
        } else {
            //modificar
            if (accion.equals("imagen")) {
                try {
                    String sql3 = "UPDATE public.productos\n"
                            + "   SET   prod_imagen=? "
                            + " WHERE id_prod=?;";
                    PreparedStatement pima = bd.conexion.prepareStatement(sql3);
                    pima.setBinaryStream(1, fis, longitudBytes);

                    pima.setInt(2, Integer.parseInt(txtid.getText()));

                    pima.execute();
                    pima.close();

                    JOptionPane.showMessageDialog(null, "Imagen Actualizada", "Informe", JOptionPane.INFORMATION_MESSAGE);
                    cargar_tabla();

                    btcancelar.doClick();

                } catch (Exception e) {

                    System.out.println("error en guardar la nueva imagen" + e);

                }
            } else {
                try {
                    String sql3 = "UPDATE public.productos\n"
                            + "   SET   prod_preciov=?, prod_cod = ? , prod_descri =? , id_marca = ?"
                            + " WHERE id_prod=?;";
                    PreparedStatement p3 = bd.conexion.prepareStatement(sql3);
                    p3.setInt(5, Integer.parseInt(txtid.getText()));

                    p3.setString(1, txtpreciov.getText());
                    p3.setString(2, txtcodigo.getText());
                    p3.setString(3, txtdescripcion.getText());
                    p3.setInt(4, Integer.parseInt(txtidmarca.getText()));
                    p3.execute();
                    p3.close();

                    JOptionPane.showMessageDialog(null, "Registro Actualizado", "Informe", JOptionPane.INFORMATION_MESSAGE);
                    cargar_tabla();

                    btcancelar.doClick();

                } catch (Exception e) {

                    System.out.println("error en la actualizacion" + e);

                }

            }
            //despues de la modificacion cierra el formulario para evitar problemas de parametros
           // dispose();
        }
    }//GEN-LAST:event_btgrabarActionPerformed

