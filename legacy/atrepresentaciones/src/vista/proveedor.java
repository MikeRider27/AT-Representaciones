    private void cargar_tabla() {
        DefaultTableModel tab = (DefaultTableModel) tabla.getModel();
        tab.setRowCount(0);

        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos("SELECT id_proveedor, prov_nombre, prov_ruc, prov_telef, prov_direc, \n"
                    + "       prov_correo, id_estado\n"
                    + "  FROM proveedor where id_estado=1 and (prov_nombre ::text ilike'%" + txtbuscar.getText() + "%' or prov_ruc ::text ilike'%" + txtbuscar.getText() + "%' ) ORDER BY id_proveedor DESC  ");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("id_proveedor"),
                    bd.resultado.getString("prov_nombre"),
                    bd.resultado.getString("prov_ruc"),
                    bd.resultado.getString("prov_telef"),
                    bd.resultado.getString("prov_direc"),
                    bd.resultado.getString("prov_correo")});

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
        }

    }
