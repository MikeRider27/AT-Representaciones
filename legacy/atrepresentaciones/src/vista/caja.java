    private void btgrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgrabarActionPerformed
        if (txtmonto.getText().trim().isEmpty()) {  //si el campo esta vacio
            JOptionPane.showMessageDialog(null, "Verifique Monto", "Error", JOptionPane.INFORMATION_MESSAGE);
            txtmonto.requestFocus();
            return;
        }
        int mensaje = JOptionPane.showConfirmDialog(null, "Desea Guardar", "Atencion", JOptionPane.YES_NO_OPTION);
        if (mensaje == JOptionPane.YES_OPTION) {
            if (accion.equals("nuevo")) {
                //guardar
                try {
                    String sql = "INSERT INTO public.apert_cierre(\n"
                            + "            id_apertcierre, apert_fecha, id_caja,  apert_monto, cierre_montefectivo, \n"
                            + "            cierre_montcheque, cierre_monttarjeta, id_estado,id_usuario)\n"
                            + "    VALUES (?, ?, ?, ?, ?, ?, \n"
                            + "            ?, ?, ?);";
                    PreparedStatement p = bd.conexion.prepareStatement(sql);
                    p.setInt(1, Integer.parseInt(txtid.getText()));
                    p.setString(2, txtfecha.getText());
                    p.setInt(3, 1);
                    p.setString(4, txtmonto.getText());
                    p.setString(5, "0");
                    p.setString(6, "0");
                    p.setString(7, "0");
                    p.setInt(8, 1);
                    p.setInt(9, Integer.parseInt(txtusuario.getText()));
                    p.execute();
                    cargar_tabla();
                    btcancelar.doClick();
                } catch (Exception e) {
                    System.out.println(e);

                }
            } else {
//            modificar
            }

        }


    }//GEN-LAST:event_btgrabarActionPerformed

