    private void btgrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgrabarActionPerformed

        int saldo = Integer.parseInt(txtsaldo.getText().replace(".", ""));
        if (saldo <= 0) {
            JOptionPane.showMessageDialog(null, "Favor Verifique Saldo", "Informe", JOptionPane.ERROR_MESSAGE);
            txtsaldo.requestFocus();
            return;
        }

        //grabar
        if (accion.equals("nuevo")) {
            // guardar
            int vcar = Integer.parseInt(txtsaldo.getText().replace(".", ""));
            int vsald = Integer.parseInt(txtsaldoactual.getText().replace(".", ""));
            int suma = (vcar + vsald);

            try {
                String sql = "INSERT INTO public.billetera(\n"
                        + "            id_billetera, id_operadora, billetera_fecha, billetera_saldoinicial, \n"
                        + "            billetera_saldoactual, billetera_hora, id_usuario)\n"
                        + "    VALUES (?, ?, ?, ?, \n"
                        + "            ?, ?, ?);";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(1, Integer.parseInt(txtid.getText()));
                p.setInt(2, Integer.parseInt(txttipo.getText()));
                p.setString(3, txtfecha.getText());
                p.setString(4, txtsaldo.getText());
                p.setString(5, formateador.format(suma).toString());
                p.setString(6, txthora.getText());
                p.setInt(7, 1);
                p.execute();
                p.close();
                //cargar_tabla();
                // System.out.println("suma" + suma);

                JOptionPane.showMessageDialog(null, "Registro Guardado", "Infomación", JOptionPane.INFORMATION_MESSAGE);
                btcancelar.doClick();

            } catch (Exception e) {
                System.out.println("error" + e);
                JOptionPane.showMessageDialog(null, "Error al grabar", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } else {
            //modificar
            int vcar = Integer.parseInt(txtsaldo.getText().replace(".", ""));
            int vsald = Integer.parseInt(txtsaldoactual.getText().replace(".", ""));
            int suma = (vcar + vsald);
            try {
                String sql = "UPDATE public.billetera\n"
                        + "   SET  id_operadora=?, billetera_fecha=?, billetera_saldoinicial=?, \n"
                        + "       billetera_saldoactual=?, billetera_hora=?, id_usuario=?\n"
                        + " WHERE id_billetera=?;";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(7, Integer.parseInt(txtid.getText()));
                p.setInt(1, Integer.parseInt(txttipo.getText()));
                p.setString(2, txtfecha.getText());
                p.setString(3, txtsaldo.getText());
                p.setString(4, formateador.format(suma).toString());
                p.setString(5, txthora.getText());
                p.setInt(6, 1);
                p.execute();
                p.close();
                //cargar_tabla();
                // System.out.println("suma" + suma);
                btcancelar.doClick();
                JOptionPane.showMessageDialog(null, "Registro Actualizado", "Infomación", JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error al actualizar", "Error", JOptionPane.ERROR_MESSAGE);
                //                System.out.println(e);
            }
        }
    }//GEN-LAST:event_btgrabarActionPerformed

