    private void cargar_saldoactual() {
        try {
            bd.listar_datos(" Select billetera_saldoactual from billetera where id_operadora = '" + txttipo.getText() + "' order by billetera_fecha desc , billetera_hora  DESC limit 1;");
            if (bd.resultado.next()) {
                txtsaldoactual.setText(bd.resultado.getString("billetera_saldoactual"));
            }
        } catch (Exception e) {
            System.out.println("error en:" + e);
            JOptionPane.showMessageDialog(null, "Error al recuperar saldo" + e);
        }
    }

    private void cargar_tabla() {
        DefaultTableModel tab = (DefaultTableModel) tabla.getModel();
        tab.setRowCount(0);

        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos("SELECT b.id_billetera as id,op.op_descri as descri, b.billetera_fecha as fecha,b.billetera_saldoinicial as saldo,\n"
                    + "           b.billetera_saldoactual as saldoactual, b.billetera_hora as hora  FROM billetera b \n"
                    + "                    inner join operadoras op on op.id_operadora = b.id_operadora\n"
                    + "                    where b.id_operadora =  '" + txtcbtipo.getText() + "' order by billetera_fecha desc , billetera_hora  DESC limit 1;");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("id"),
                    bd.resultado.getString("descri"),
                    bd.resultado.getString("fecha"),
                    bd.resultado.getString("saldo"),
                    bd.resultado.getString("saldoactual"),
                    bd.resultado.getString("hora")});

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
        }
    }

