    private void btmodificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btmodificarActionPerformed
        if (txtid.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Seleccione un registro", "Informe", JOptionPane.INFORMATION_MESSAGE);
        } else {
            accion = "modificar";
            txtbuscar.setText("");
            btcancelar.setEnabled(true);
            btnuevo.setEnabled(false);
            btmodificar.setEnabled(false);
            btgrabar.setEnabled(true);
            txtdescripcion.requestFocus();
            txtdescripcion.setEnabled(true);

            cargar_tabla();
        }
    }//GEN-LAST:event_btmodificarActionPerformed

    private void btgrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgrabarActionPerformed
        if (txtdescripcion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe Ingresar Descripción", "Informe", JOptionPane.INFORMATION_MESSAGE);
            txtdescripcion.requestFocus();
            return;
        }

        //grabar
        if (accion.equals("nuevo")) {

            //guardar
            try {
                String sql = "INSERT INTO public.marca(\n"
                        + "            id_marca, mar_descri)\n"
                        + "    VALUES (?, ?);";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(1, Integer.parseInt(txtid.getText()));
                p.setString(2, txtdescripcion.getText());
                p.execute();
                cargar_tabla();
                btcancelar.doClick();
               JOptionPane.showMessageDialog(null, "Registro Guardado", "Informe", JOptionPane.INFORMATION_MESSAGE);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error al guardar los datos" + e);
            }

            //dispose();
        } else {
            //          modificar
            try {

                String sql = "UPDATE public.marca\n"
                        + "   SET  mar_descri=?\n"
                        + " WHERE id_marca=?;";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(2, Integer.parseInt(txtid.getText()));
                p.setString(1, txtdescripcion.getText());
                p.execute();;
                //cargar la tabla una vez registrado
                cargar_tabla();

                btcancelar.doClick();
                 JOptionPane.showMessageDialog(null, "Registro Actualizado", "Informe", JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception e) {
                //                System.out.println(e);
                JOptionPane.showMessageDialog(null, "Error" + e);

            }

        }
    }//GEN-LAST:event_btgrabarActionPerformed

