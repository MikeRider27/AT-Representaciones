    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        lblfoto.setIcon(null);
        JFileChooser j = new JFileChooser();
        j.setFileSelectionMode(JFileChooser.FILES_ONLY);
        int estado = j.showOpenDialog(null);
        if (estado == JFileChooser.APPROVE_OPTION) {
            try {
                fis = new FileInputStream(j.getSelectedFile());
                //necesitamos saber la cantidad de bytea
                this.longitudBytes = (int) j.getSelectedFile().length();
                try {
                    Image icono = ImageIO.read(j.getSelectedFile()).getScaledInstance(lblfoto.getWidth(), lblfoto.getHeight(), Image.SCALE_DEFAULT);
                    lblfoto.setIcon(new ImageIcon(icono));
                    lblfoto.updateUI();

                } catch (Exception e) {
                    JOptionPane.showMessageDialog(rootPane, "imagen" + e);
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        ImageIcon foto;
        InputStream is;
        String nombre;
        try {
            bd.listar_datos("SELECT codigo, nombre, foto FROM personas where codigo = " + txtcodigo.getText() + "");
            while (bd.resultado.next()) {                
                is = bd.resultado.getBinaryStream(3);
                nombre = bd.resultado.getString(2);
                
                BufferedImage bi= ImageIO.read(is);
                foto = new ImageIcon(bi);
                
                Image img = foto.getImage();
                Image newimg = img.getScaledInstance(140, 170, java.awt.Image.SCALE_SMOOTH);
                
                ImageIcon newicon = new ImageIcon(newimg);
                lblfoto.setIcon(newicon);
                txtdescripcion.setText(nombre);
                
                
            }
        } catch (Exception e) {
            System.out.println("error en la bd" + e);
        }


    }//GEN-LAST:event_jButton3ActionPerformed

