    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String sql = "INSERT INTO public.personas(\n"
                    + "            codigo, nombre, foto)\n"
                    + "    VALUES (?, ?, ?);";
            PreparedStatement ps = bd.conexion.prepareStatement(sql);
            ps.setInt(1, Integer.parseInt(txtcodigo.getText()));
            ps.setString(2, txtdescripcion.getText());
            ps.setBinaryStream(3, fis, longitudBytes);
            ps.execute();
            ps.close();

            lblfoto.setIcon(null);
            txtcodigo.setText("");
            txtdescripcion.setText("");
            JOptionPane.showMessageDialog(rootPane, "Grabado");
        } catch (Exception e) {
            System.out.println("erro:" + e);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

