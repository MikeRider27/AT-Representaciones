    private void btgrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btgrabarActionPerformed
        if (txtmonto.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe Ingresar Monto de Venta", "Informe", JOptionPane.ERROR_MESSAGE);
            txtmonto.requestFocus();
            return;
        }
        int monto = Integer.parseInt(txtmonto.getText().replace(".", ""));
        int saldo = Integer.parseInt(txtsaldo.getText().replace(".", ""));
        if (monto <= 0) {
            JOptionPane.showMessageDialog(null, "Favor Verifique Monto", "Informe", JOptionPane.ERROR_MESSAGE);
            txtsaldo.requestFocus();
            return;
        }

        if (txtnumero.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Debe Ingresar Numero Telefonico", "Informe", JOptionPane.ERROR_MESSAGE);
            txtnumero.requestFocus();
            return;
        }

        if (saldo <= 0) {
            JOptionPane.showMessageDialog(null, "Debe Cargar Saldo para la venta", "Informe", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (saldo < monto) {
            JOptionPane.showMessageDialog(null, "Verifique los montos ingresados\n Error en monto para carga", "Informe", JOptionPane.ERROR_MESSAGE);
            txtmonto.requestFocus();
            return;
        }
        if (txtcarga.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Favor Ingrese Tipo de Carga", "Informe", JOptionPane.ERROR_MESSAGE);
            txtcarga.requestFocus();
            return;
        }
        //grabar
        if (accion.equals("nuevo")) {
            // guardar
//            int vcar = Integer.parseInt(txtsaldo.getText().replace(".", ""));
//            int vsald = Integer.parseInt(txtsaldoactual.getText().replace(".", ""));
//            int suma = (vcar + vsald);

            try {
                String sql = "INSERT INTO public.venta_saldo(\n"
                        + "            id_ventasaldo, vent_monto, vent_numero, id_operadora, id_usuario, \n"
                        + "            id_carga, id_estado,vent_fecha,id_apertcierre)\n"
                        + "    VALUES (?, ?, ?, ?, ?, \n"
                        + "            ?, ?,?,?);";
                PreparedStatement p = bd.conexion.prepareStatement(sql);
                p.setInt(1, Integer.parseInt(txtid.getText()));
                p.setString(2, txtmonto.getText());
                p.setString(3, txtnumero.getText());
                p.setInt(4, Integer.parseInt(txtoperadora.getText()));
                p.setInt(5, 1);  //usuario 1
                p.setInt(6, Integer.parseInt(txtcarga.getText()));
                p.setInt(7, 1);
                p.setString(8, txtfecha.getText());
                p.setInt(9, Integer.parseInt(txtapertura.getText()));
                p.execute();
                p.close();

                // System.out.println("suma" + suma);
                JOptionPane.showMessageDialog(null, "Registro Guardado", "Infomación", JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception e) {
                System.out.println("error" + e);
                JOptionPane.showMessageDialog(null, "Error al grabar", "Error", JOptionPane.ERROR_MESSAGE);
            }
            bd.autonumerico("cobro", "id_cobro", txtidcobro);
            try {
                String sqlcobro = "INSERT INTO public.cobro(\n"
                        + "            id_cobro, cobro_descri, id_estado,cobro_total,id_apertcierre)\n"
                        + "    VALUES (?, ?, ?,?,?);";
                PreparedStatement cobro = bd.conexion.prepareStatement(sqlcobro);
                cobro.setInt(1, Integer.parseInt(txtidcobro.getText()));
                cobro.setString(2, "Cobro de Carga de Saldo");
                cobro.setInt(3, 1);
                cobro.setString(4, txtmonto.getText());
                cobro.setInt(5, Integer.parseInt(txtapertura.getText()));
                cobro.execute();
                cobro.close();

                String sqlcobrodet = "INSERT INTO public.detalle_cobro(\n"
                        + "            id_cobro, id_ventasaldo, det_monto)\n"
                        + "    VALUES (?, ?, ?);";
                PreparedStatement cobrodet = bd.conexion.prepareStatement(sqlcobrodet);
                cobrodet.setInt(1, Integer.parseInt(txtidcobro.getText()));
                cobrodet.setInt(2, Integer.parseInt(txtid.getText()));
                cobrodet.setString(3, txtmonto.getText());
                cobrodet.execute();
                cobrodet.close();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "error al grabar cobro" + e);
                System.out.println("erro en" + e);
            }
            btcancelar.doClick();
            sumatigo();
            sumapersonal();
            sumaclaro();
            sumavox();
            suma();
        } else {

        }


    }//GEN-LAST:event_btgrabarActionPerformed

