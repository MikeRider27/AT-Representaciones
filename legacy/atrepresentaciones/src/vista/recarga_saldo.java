    private void cargar_tabla() {
        DefaultTableModel tab = (DefaultTableModel) tabla.getModel();
        tab.setRowCount(0);

        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos(" SELECT v.id_ventasaldo as codigo, v.vent_monto as monto,"
                    + " v.vent_numero as numero, op.op_descri as operadora, v.id_usuario as usuario, \n"
                    + "       ca.carg_descri as obs, v.id_estado as estado, v.vent_fecha as fecha\n"
                    + "  FROM venta_saldo v\n"
                    + "inner join operadoras op on op.id_operadora = v.id_operadora\n"
                    + "inner join carga ca on ca.id_carga = v.id_carga\n"
                    + "\n"
                    + " where id_estado = 1  order by v.id_ventasaldo desc;");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("numero"),
                    bd.resultado.getString("monto"),
                    bd.resultado.getString("obs"),
                    bd.resultado.getString("fecha"),
                    bd.resultado.getString("operadora")});

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
        }
    }

    private void cargar_saldoactual() {
        try {
            bd.listar_datos(" Select operad_saldoactual from recarga_operadoras where id_operadora = '" + txtoperadora.getText() + "' order by operad_fecha desc , operad_hora  DESC limit 1;");

            if (bd.resultado.next()) {
                txtsaldo.setText(bd.resultado.getString("operad_saldoactual"));

            }

        } catch (Exception e) {
            System.out.println("error en:" + e);
            JOptionPane.showMessageDialog(null, "Error al recuperar saldo" + e);
        }
    }

