    private void cargar_tabla() {
        //select de la caja activa
        DefaultTableModel tab = (DefaultTableModel) tablaresumen.getModel();
        tab.setRowCount(0);

        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos(" SELECT id_cobro, cobro_descri, id_estado, cobro_total\n"
                    + "  FROM public.cobro where id_estado = 1;");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("id_cobro"),
                    bd.resultado.getString("cobro_descri"),
                    bd.resultado.getString("id_estado"),
                    bd.resultado.getString("cobro_total")});

            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
        }
        suma();
    }

    private void recuperar_cobro() {
        DefaultTableModel tab = (DefaultTableModel) tablaarqueo.getModel();
        tab.setRowCount(0);

        try {
            // ilike busca las letras por mayusculas y minisculas
            bd.listar_datos(" select id_apertcierre,apert_fecha,apert_monto,id_estado from apert_cierre where id_estado = 1"
                    + "");
            while (bd.resultado.next()) {
                tab.addRow(new Object[]{bd.resultado.getString("id_apertcierre"),
                    bd.resultado.getString("apert_fecha"),
                    bd.resultado.getString("apert_monto"),
                    bd.resultado.getString("id_estado")});
                txtfecha.setText(bd.resultado.getString("apert_fecha"));
                txtid.setText(bd.resultado.getString("id_apertcierre"));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error al cargar la tabla" + e);
        }

    }

    private void suma() {
        int vtotal = 0;
        for (int i = 0; i < tablaresumen.getRowCount(); i++) {
            //Toma el monto de la columna sub total en la variable vtot
            int vtot = Integer.parseInt(tablaresumen.getValueAt(i, 3).toString().replace(".", ""));
            vtotal = vtotal + vtot;
//             vtotexe += vtot;
        }
        int vtotalefe = 0;
        txtefectivo.setText(formateador.format(vtotal));
        for (int i = 0; i < tablaarqueo.getRowCount(); i++) {
            //Toma el monto de la columna sub total en la variable vtot
            int vaper = Integer.parseInt(tablaarqueo.getValueAt(i, 2).toString().replace(".", ""));
            vtotalefe = vtotalefe + vaper;
//             vtotexe += vtot;
        }
        txtmontoinicio.setText(formateador.format(vtotalefe));

        String vretiro = "";
        //retiro de dinero
        int v1 = 0;
        for (int i = 0; i < tablaresumen.getRowCount(); i++) {

            //Toma el monto de la columna sub total en la variable vtot
            String vret = (tablaresumen.getValueAt(i, 1).toString());

            vretiro = vret;
            //System.out.println(vretiro);
            if (vretiro.equals("Retiro de Dinero Billetera")) {
                int v2 = Integer.parseInt(tablaresumen.getValueAt(i, 3).toString().replace(".", ""));
                v1 = v1 + v2;
            }
            txtretiro.setText(formateador.format(v1));

            txtmontototal.setText(formateador.format(vtotal + vtotalefe - v1));
        }
    }

    private void grabar() {
        if (accion.equals("nuevo")) {

            try {
                //grabar apertura
                String sqlapertura = "UPDATE public.apert_cierre\n"
                        + "   SET  cierre_montefectivo=?, \n"
                        + "       cierre_montcheque=?, cierre_monttarjeta=?, id_estado=?\n"
                        + " WHERE id_apertcierre=?;";
                PreparedStatement apert = bd.conexion.prepareStatement(sqlapertura);
                apert.setInt(5, Integer.parseInt(txtid.getText()));
                apert.setString(1, txtmontototal.getText());
                apert.setString(2, txtcheque.getText());
                apert.setString(3, txttarjeta.getText());
                apert.setInt(4, 3);
                apert.execute();
                apert.close();

                //grabar arqueo
                String sqlarq = "INSERT INTO public.arqueo(\n"
                        + "            id_arqueo, id_apertcierre, arq_montoefectivo, arq_montocheque, \n"
                        + "            arq_montotarjeta)\n"
                        + "    VALUES (?, ?, ?, ?, \n"
                        + "            ?);";
                PreparedStatement arq = bd.conexion.prepareStatement(sqlarq);
                arq.setInt(1, Integer.parseInt(txtarqueo.getText()));
                arq.setInt(2, Integer.parseInt(txtid.getText()));
                arq.setString(3, txtmontototal.getText());
                arq.setString(4, txtcheque.getText());
                arq.setString(5, txttarjeta.getText());
                arq.execute();
                arq.close();

                // cierre de cobro
                
                
                //limpiar campos
                DefaultTableModel tab = (DefaultTableModel) tablaarqueo.getModel();
                tab.setRowCount(0);
                DefaultTableModel tabla = (DefaultTableModel) tablaresumen.getModel();
                tabla.setRowCount(0);
                txtefectivo.setText("0");
                txtmontoinicio.setText("0");
                txtmontototal.setText("0");
                txtretiro.setText("0");
                txttarjeta.setText("0");
                txtcheque.setText("0");
                txtfecha.setText("00/00/0000");
                txtid.setText("0");
                accion = "";

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "error al grabar arqueo y apertura" + ex);
            }

        }
    }

   
